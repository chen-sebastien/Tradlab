import {test,expect} from '@playwright/test'
import fs from 'node:fs'
import path from 'node:path'

test('CSV、回測、研究、模擬委託與風控介面完整流程',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/')
 await page.getByLabel('本機存取權杖',{exact:true}).fill(fs.readFileSync(path.resolve('../.local/e2e-client-token.txt'),'utf8').trim())
 await page.getByRole('button',{name:'連接 TradingLab',exact:true}).click()
 await expect(page.getByText('100,000',{exact:true}).first()).toBeVisible()
 await expect(page.getByText('● 運作中',{exact:true})).toHaveCount(4,{timeout:15000})
 await page.getByRole('button',{name:'策略與提案',exact:true}).click()
 await page.getByLabel('限價（TWD）',{exact:true}).fill('48.5')
 await page.getByLabel('數量（股）',{exact:true}).fill('90')
 await page.getByRole('button',{name:'送出風控審核',exact:true}).click()
 await page.getByRole('button',{name:'確認模擬委託',exact:true}).click()
 await expect(page.getByRole('cell',{name:'已受理',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'儀表板',exact:true}).click()
 await page.getByRole('button',{name:'推進一個交易日 →',exact:true}).click()
 await page.getByRole('button',{name:'模擬帳戶',exact:true}).click()
 await expect(page.getByRole('cell',{name:'部分成交',exact:true})).toBeVisible()
 await expect(page.getByRole('cell',{name:'90 / 56',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'撤單',exact:true}).click()
 await expect(page.getByRole('cell',{name:'已撤單',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'回測實驗室',exact:true}).click()
 await page.getByRole('button',{name:'執行回測',exact:true}).click()
 await expect(page.getByRole('heading',{name:'回測結果',exact:true})).toBeVisible({timeout:30000})
 await expect(page.getByRole('cell',{name:'最大回撤',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'研究中心',exact:true}).click()
 await page.getByRole('button',{name:'啟動研究',exact:true}).click()
 await expect(page.getByText('Walk-forward 平衡準確度',{exact:true})).toBeVisible({timeout:30000})
 await expect(page.getByText('MA5 / MA20 規則策略',{exact:true})).toBeVisible()
 await page.getByRole('button',{name:'行情與資料',exact:true}).click()
 await page.getByLabel('資料來源名稱',{exact:true}).fill('E2E synthetic fixture')
 await page.getByLabel('CSV 內容',{exact:true}).fill('date,open,high,low,close,volume\n2024-01-02,40,42,39,41,20000\n2024-01-03,41,43,40,42,30000')
 await page.getByRole('button',{name:'檢查並匯入',exact:true}).click()
 await expect(page.getByText('2024-01-02 → 2024-01-03')).toBeVisible()
 await page.getByRole('button',{name:'風控與監察',exact:true}).click()
 await page.getByRole('button',{name:'停止新增風險',exact:true}).click()
 await expect(page.getByRole('button',{name:'恢復新增風險',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'設定',exact:true}).click()
 await expect(page.getByRole('button',{name:'LIVE 尚未開放',exact:true})).toBeDisabled()
 await page.getByRole('button',{name:'儀表板',exact:true}).click()
 await expect(page.locator('.q-notification')).toHaveCount(0,{timeout:10000})
 await page.screenshot({path:'../artifacts/dashboard-desktop.png',fullPage:true})
 await page.setViewportSize({width:390,height:844})
 await expect(page.getByRole('heading',{name:'儀表板',exact:true})).toBeVisible()
 await page.screenshot({path:'../artifacts/dashboard-mobile.png',fullPage:true})
 expect(errors).toEqual([])
})
